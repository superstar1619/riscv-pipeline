"""Publishing reports must never copy raw evidence into the documentation tree."""
from pathlib import Path
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'scripts/lib'))
import cvw_common as common


class ReportPublishTests(unittest.TestCase):
    def test_direct_scheduler_keeps_bytecode_in_target(self):
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            shutil.copytree(ROOT / 'scripts', root / 'scripts',
                            ignore=shutil.ignore_patterns('__pycache__'))
            env = dict(os.environ)
            env.pop('PYTHONPYCACHEPREFIX', None)
            env.pop('PYTHONDONTWRITEBYTECODE', None)
            result = subprocess.run([sys.executable, root / 'scripts/run/verify.py', '--plan'],
                                    cwd=root, env=env, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(json.loads(result.stdout)['profile'], 'smoke')
            self.assertFalse(list((root / 'scripts').rglob('__pycache__')),
                             'direct entrypoint left generated bytecode beside source')

    def test_publishes_only_reports_and_rebases_nested_links(self):
        self.assertTrue(callable(getattr(common, 'publish_reports', None)),
                        'Markdown-only report publisher is missing')
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            run = root / 'target/run'
            docs = root / 'docs/reports/run'
            (run / 'chapter').mkdir(parents=True)
            (run / 'source').mkdir()
            (run / 'results.json').write_text('{"status":"cpu_failure"}')
            (run / 'chapter/detail.md').write_text('[raw](../results.json#failure)\n')
            (run / 'source/README.md').write_text('source snapshot')
            text = '# Failed run\n[detail](chapter/detail.md) [raw](results.json)\n[web](https://example.org)\n'
            (run / 'report.md').write_text(text)
            common.publish_reports(run, docs, 'make report-verification')
            self.assertEqual(sorted(str(p.relative_to(docs)) for p in docs.rglob('*') if p.is_file()),
                             ['chapter/detail.md', 'report.md'])
            report = (docs / 'report.md').read_text()
            self.assertIn('[detail](chapter/detail.md)', report)
            self.assertIn('[raw](../../../target/run/results.json)', report)
            self.assertIn('[web](https://example.org)', report)
            self.assertIn('../../../../target/run/results.json#failure', (docs / 'chapter/detail.md').read_text())
            self.assertIn('make report-verification', report)
            self.assertEqual((run / 'report.md').read_text(), text)

    def test_published_report_survives_evidence_cleanup(self):
        self.assertTrue(callable(getattr(common, 'publish_reports', None)),
                        'Markdown-only report publisher is missing')
        with tempfile.TemporaryDirectory() as name:
            root = Path(name)
            run = root / 'target/run'
            run.mkdir(parents=True)
            (run / 'report.md').write_text('# Run\n')
            common.publish_reports(run, root / 'docs', 'make report-verification')
            (run / 'report.md').unlink()
            text = (root / 'docs/report.md').read_text()
            self.assertIn('target/', text)
            self.assertIn('clean', text)


if __name__ == '__main__':
    unittest.main()
